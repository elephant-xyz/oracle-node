/**
 * Resolve county metadata with fallback to Volusia.
 * @param {string} key
 * @returns {CountyMetadata}
 */
export function getCountyMetadata(key) {
  const normKey = (key || "").toLowerCase().trim();
  return COUNTY_REGISTRY[normKey] || COUNTY_REGISTRY.volusia;
}

/**
 * List all available counties.
 * @returns {CountyMetadata[]}
 */
export function listCounties() {
  return Object.values(COUNTY_REGISTRY);
}
